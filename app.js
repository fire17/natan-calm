  function rampDuck(to, sec) {
    const g = duck.gain, t = ctx.currentTime;
    g.cancelScheduledValues(t);
    g.setValueAtTime(Math.max(g.value, 0.0001), t);
    g.exponentialRampToValueAtTime(to, t + sec);
  }
