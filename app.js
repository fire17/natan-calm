  // Buffers are generated in small chunks (one step = CHUNK samples), so no single task blocks the page.
  const CHUNK = 16384;
  function noiseJob(type, seconds = 8) {
    const sr = ctx.sampleRate, len = Math.floor(sr * seconds), b = ctx.createBuffer(2, len, sr);
    let c = 0, i = 0, b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0, last = 0;
    return () => {
      const d = b.getChannelData(c), stop = Math.min(len, i + CHUNK);
      for (; i < stop; i++) {
        const w = Math.random() * 2 - 1;
        if (type === 'white') d[i] = w * 0.5;
        else if (type === 'pink') {
          b0 = 0.99886 * b0 + w * 0.0555179; b1 = 0.99332 * b1 + w * 0.0750759;
          b2 = 0.969 * b2 + w * 0.153852; b3 = 0.8665 * b3 + w * 0.3104856;
          b4 = 0.55 * b4 + w * 0.5329522; b5 = -0.7616 * b5 - w * 0.016898;
          d[i] = (b0 + b1 + b2 + b3 + b4 + b5 + b6 + w * 0.5362) * 0.11;
          b6 = w * 0.115926;
        } else {
          last = (last + 0.02 * w) / 1.02;
          d[i] = last * 3.5;
        }
      }
      if (i < len) return false;
      // crossfade loop seam
      const fade = Math.floor(sr * 0.05);
      for (let k = 0; k < fade; k++) {
        const t = k / fade;
        d[len - fade + k] = d[len - fade + k] * (1 - t) + d[k] * t;
      }
      i = 0; b0 = b1 = b2 = b3 = b4 = b5 = b6 = last = 0;
      if (++c < 2) return false;
      buf[type] = b;
      return true;
    };
  }

  // v0.6: 2.8s IR (was 4.5s); decay exponent lowered so the first ~1s of the tail matches the old one
  function impulseJob(seconds, decay, done) {
    const sr = ctx.sampleRate, len = Math.floor(sr * seconds), b = ctx.createBuffer(2, len, sr);
    let c = 0, i = 0, lp = 0;
    return () => {
      const d = b.getChannelData(c), stop = Math.min(len, i + CHUNK);
      for (; i < stop; i++) {
        const w = Math.random() * 2 - 1;
        lp = lp + 0.35 * (w - lp); // gentle darkening
        d[i] = lp * Math.pow(1 - i / len, decay);
      }
      if (i < len) return false;
      i = 0; lp = 0;
      if (++c < 2) return false;
      done(b);
      return true;
    };
  }

